export function getRegionsForGovernorate(governorateName?: string): string[] {
  if (!governorateName) return [];
  const gov = GOVERNORATES_DATA.find(
    (g) => g.name.trim().toLowerCase() === governorateName.trim().toLowerCase()
  );
  return gov ? gov.regions : [];
}
